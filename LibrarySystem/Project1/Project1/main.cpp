// =====================================================================
// main.cpp  ——  阶段二演示：组合关系 + 依赖关系（实验二）
// ---------------------------------------------------------------------
// 【本阶段要演示的两种类关系】
//   组合关系（has a）：
//       Library  ⊃ Book、Reader            （图书馆包含图书/读者）
//       Reader   ⊃ BorrowRecord            （读者包含借阅记录）
//       BorrowRecord ⊃ Date                （记录包含日期）
//   依赖关系（use a）：
//       Reader::borrowBook(Book*, Date&)   （读者借书时"用到"图书）
//
// 【演示顺序】
//   先把"整体"装配起来（组合），再发起"借阅动作"（依赖），
//   最后观察双方状态的变化 —— 这正是依赖关系的验证方式。
// =====================================================================

#include "Library.h"
#include "Book.h"
#include "Reader.h"
#include "BorrowRecord.h"
#include "Date.h"

#include <iostream>
#include <limits>

// ---------------------------------------------------------------------
// 辅助：分节标题（让输出有条理）
// ---------------------------------------------------------------------
static void section(const std::string& title) {
    std::cout << "\n==================== " << title << " ====================\n";
}

// ---------------------------------------------------------------------
// 辅助：暂停等回车（演示时一屏一屏看）
// ---------------------------------------------------------------------
static void pause() {
    std::cout << "\n（按回车键继续...）";
    std::cin.ignore(std::numeric_limits<std::streamsize>::max(), '\n');
}

int main() {
    std::cout << "########## 阶段二演示：组合关系 + 依赖关系 ##########\n";

    // =================================================================
    // 演示 0：先认识一下本阶段新增的工作人员
    // -----------------------------------------------------------------
    // 【目的】在正式演示前，先看看 Date 类能不能正确做日期运算。
    //   日期算不对，后面逾期判断全是错的，所以先单独验一遍。
    // =================================================================
    section("0. Date 类：日期运算基础");

    Date d1(2026, 9, 19);
    Date d2 = d1.addDays(30);          // 借出日 + 30 天 = 应还日
    std::cout << "借出日期：" << d1.toString() << '\n'
        << "加 30 天后（应还日期）：" << d2.toString() << '\n'
        << "两者相差：" << d1.daysBetween(d2) << " 天\n";

    // 跨月/跨年验证，确认闰年逻辑没错
    Date nov(2026, 11, 20);
    std::cout << "2026-11-20 加 70 天 → " << nov.addDays(70).toString()
        << "（跨年验证）\n";

    Date leap(2024, 2, 28);
    std::cout << "2024-02-28 加 1 天 → " << leap.addDays(1).toString()
        << "（2024 是闰年，故为 02-29）\n";

    Date nonLeap(2025, 2, 28);
    std::cout << "2025-02-28 加 1 天 → " << nonLeap.addDays(1).toString()
        << "（2025 非闰年，故为 03-01）\n";

    // 非法日期拦截
    Date bad;
    bool ok = bad.setDate(2026, 2, 30);
    std::cout << "尝试设置 2026-02-30 → "
        << (ok ? "成功（不该发生）"
            : "被拒绝，日期保持不变（" + bad.toString() + "）")
        << '\n';
    pause();

    // =================================================================
    // 演示 1：组合关系（1）—— 图书馆 ⊃ 图书
    // -----------------------------------------------------------------
    // 【目的】先把"整体"装配起来。
    // 【观察点】Library 对象一旦创建，它内部 100 个 Book、
    //   50 个 Reader 就已经被自动构造好了 —— 这就是组合关系的
    //   "内嵌对象先被创建"。
    // 【知识点】Library has a Book → 组合关系
    // =================================================================
    section("1. 组合关系（1）：图书馆包含图书");

    Library lib;    // ★ 这一行背后：100 次 Book() + 50 次 Reader()
    //   以及 Reader 内部的 500 次 BorrowRecord() ...
    //   想验证的话，在 Book::Book() 里打断点看调用次数。

    std::cout << "图书馆已创建。\n";
    lib.print();

    std::cout << "\n开始录入馆藏图书（把书\"纳入\"图书馆）：\n";
    // addBook 接收 const Book&，内部拷贝一份进馆藏数组 —— 这就是"包含"的动作
    lib.addBook(Book("C++程序设计", "978-7-111-12345-6",
        "机械工业出版社", 59.00, 520, 2));   // 2 本复本
    lib.addBook(Book("算法导论", "9787111407010",
        "机械工业出版社", 128.00, 780, 1));   // 仅 1 本
    lib.addBook(Book("数据结构与算法分析", "9787111558545",
        "机械工业出版社", 89.00, 650, 3));   // 3 本复本
    std::cout << "录入完成，当前馆藏 " << lib.getBookCount() << " 种。\n";
    pause();

    // =================================================================
    // 演示 2：组合关系（2）—— 图书馆 ⊃ 读者
    // -----------------------------------------------------------------
    // 【目的】继续装配整体，把读者也纳入图书馆。
    // 【知识点】读者有"最大借阅图书数量"属性（课程明确要求）。
    //   这里刻意给两个读者不同的上限，方便后面演示"额度用尽"的失败场景。
    // =================================================================
    section("2. 组合关系（2）：图书馆包含读者");

    // 张三：上限 2 本（故意设小，方便演示"超额"）
    lib.addReader(Reader("2024001", "张三", "计算机科学与技术学院", 2));
    // 李四：上限 5 本
    lib.addReader(Reader("2024002", "李四", "计算机科学与技术学院", 5));

    std::cout << "录入完成，当前注册读者 " << lib.getReaderCount() << " 人。\n";
    lib.showAllReaders();
    pause();

    // =================================================================
    // 演示 3：依赖关系 —— 借书成功
    // -----------------------------------------------------------------
    // 【目的】本阶段最核心的一步。观察"双方状态同时改变"。
    // 【依赖关系的代码形态】
    //     Reader::borrowBook(Book* book, const Date& today)
    //     —— 参数里出现了 Book 的指针，构成 use a 关系。
    // 【为什么必须传指针？】
    //     指针传的是馆藏里那本真书的地址，改可借数才真的生效。
    //     下面输出里"该书可借余量"从 2 变成 1，就是证明。
    // =================================================================
    section("3. 依赖关系：借书成功（双方状态同时改变）");

    Date today(2026, 9, 19);
    std::cout << "今天日期：" << today.toString() << "\n";

    // 《C++程序设计》馆藏 2 本，可借 2 本 → 借 1 本后应剩 1 本
    lib.borrowBook("2024001", "978-7-111-12345-6", today);

    std::cout << "\n>> 查看图书当前状态（验证可借数已减少）：\n";
    Book* b = lib.findBookByIsbn("978-7-111-12345-6");
    if (b) b->print();

    std::cout << "\n>> 查看读者当前状态（验证已借数已增加）：\n";
    Reader* r = lib.findReaderById("2024001");
    if (r) r->print();
    pause();

    // =================================================================
    // 演示 4：依赖关系的边界 —— 三种借书失败场景
    // -----------------------------------------------------------------
    // 【目的】验证"借阅需要判断双方状态，都允许才能成功"这条要求。
    //   我们要刻意制造失败，证明守卫逻辑真的有效。
    // =================================================================
    section("4. 借书失败的三种情况");

    std::cout << "【场景 A】重复借同一本书（业务合理性检查）\n";
    lib.borrowBook("2024001", "978-7-111-12345-6", today);

    std::cout << "\n【场景 B】借阅额度用尽（读者侧状态检查）\n";
    std::cout << "  张三上限 2 本，目前已借 1 本，再借 1 本刚好满：\n";
    lib.borrowBook("2024001", "9787111407010", today);   // 借第 2 本 → 成功，额度用尽
    std::cout << "  此时再想借第 3 本（超额）：\n";
    lib.borrowBook("2024001", "9787111558545", today);   // 借第 3 本 → 失败

    std::cout << "\n【场景 C】图书已全部借出（图书侧状态检查）\n";
    std::cout << "  《算法导论》馆藏仅 1 本，已在场景 B 中被张三借走"
        << "（当前可借余量 0）。\n"
        << "  此时李四（额度还有 5 本）想借这本：\n";
    lib.borrowBook("2024002", "9787111407010", today);   // 无复本 → 失败
    std::cout << "  —— 注意这次失败的原因是\"书\"，不是\"人\"：\n"
        << "     李四额度充足，但馆里这一本确实在别人手上。\n"
        << "     这正说明借阅必须\"双方状态都允许\"才能成功。\n";
    pause();

    // =================================================================
    // 演示 5：还书 + 逾期罚款
    // -----------------------------------------------------------------
    // 【目的】验证还书时双方状态反向变化，并观察逾期计算。
    // 【关键】我们故意用一个"很晚"的日期来还书，触发逾期逻辑，
    //   证明阶段二埋下的日期能力是好用的（阶段七会把这套规则做完整）。
    // =================================================================
    section("5. 还书：状态回滚 + 逾期罚款");

    std::cout << "【正常归还】李四借《数据结构与算法分析》，并在应还期内归还\n";
    std::cout << "  第一步：李四借书（馆藏 3 本，可借 3→2）\n";
    lib.borrowBook("2024002", "9787111558545", today);
    std::cout << "  第二步：李四于 2026-10-01 归还（应还日 10-19，未超期）\n";
    Date soon(2026, 10, 1);
    lib.returnBook("2024002", "9787111558545", soon);

    std::cout << "\n【逾期归还】张三拖到很晚才还《C++程序设计》\n";
    std::cout << "  借出日期 2026-09-19，应还日期 2026-10-19\n";
    Date late(2026, 11, 8);      // 应还日 10-19 → 11-08，逾期 20 天
    lib.returnBook("2024001", "978-7-111-12345-6", late);

    std::cout << "\n>> 还书后再次查看图书状态（可借数应已恢复）：\n";
    Book* b2 = lib.findBookByIsbn("978-7-111-12345-6");
    if (b2) b2->print();
    pause();

    // =================================================================
    // 演示 6：组合关系的"传递性"—— 查看完整借阅记录
    // -----------------------------------------------------------------
    // 【目的】展示层层嵌套的组合结构如何协同工作：
    //     Reader ⊃ BorrowRecord ⊃ Date
    //   一次 printRecords() 调用，内部会一路调用下去。
    // =================================================================
    section("6. 组合关系的传递性：查看借阅记录");

    // ★修正13-a：字符串里的 ⊃（U+2283）在中文代码页 936（GBK）里没有对应编码，
    //   MSVC 会报 warning C4566，运行时那个字符会变成 '?'，
    //   屏幕上就成了"（Reader ? BorrowRecord ? Date）"。改成中文"包含"，含义完全一样。
    std::cout << "【张三的借阅记录】（Reader 包含 BorrowRecord 包含 Date）\n";
    Reader* zhangsan = lib.findReaderById("2024001");
    if (zhangsan) zhangsan->printRecords(today);

    std::cout << "\n【李四的借阅记录】\n";
    Reader* lisi = lib.findReaderById("2024002");
    if (lisi) lisi->printRecords(today);
    pause();

    // =================================================================
    // 演示 7：整体视角
    // -----------------------------------------------------------------
    // 【目的】从图书馆这个"整体"的角度看全部资源，
    //   体会组合关系带来的好处：一个对象管住了所有部件。
    // =================================================================
    section("7. 整体视角：图书馆全景");

    lib.print();
    std::cout << "\n馆藏清单：\n";
    lib.showAllBooks();

    std::cout << "\n读者清单：\n";
    lib.showAllReaders();
    pause();

    // =================================================================
    // 收尾
    // =================================================================
    section("阶段二演示结束");

    std::cout << "本阶段两种类关系的落点：\n\n";
    std::cout << "  组合关系（has a）—— 用\"成员变量\"实现\n"
        << "    · Library      包含 Book / Reader     （图书馆拥有馆藏和读者）\n"
        << "    · Reader       包含 BorrowRecord[10]  （读者拥有借阅记录）\n"
        // ★同修正13-a：这三行的 ⊃ 也换掉，否则收尾总结会打印成一堆 '?'
        << "    · BorrowRecord 包含 Date ×2           （记录拥有借出/应还日期）\n\n";
    std::cout << "  依赖关系（use a）—— 用\"函数参数指针\"实现\n"
        << "    · Reader::borrowBook(Book* book, const Date& today)\n"
        << "    · Reader::returnBook(Book* book, const Date& today)\n\n";
    std::cout << "  关键结论：\n"
        << "    参数必须传地址（指针/引用），否则改的是副本，借书会\"假成功\"。\n";

    std::cout << "\n按回车键退出程序。";
    std::cin.ignore(std::numeric_limits<std::streamsize>::max(), '\n');

    return 0;
}
